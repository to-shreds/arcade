import assert from 'node:assert/strict';
import '../mad-libs/word-case.js';
const { format, render } = globalThis.ArcadeMadLibsCase;
const escape = text => text.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
assert.equal(format('Red', 'color', false), 'red');
assert.equal(format('Very Big', 'adjective', false), 'very big');
assert.equal(format('I Forgot My Lunch', 'exclamation', false), 'I forgot my lunch');
assert.equal(format('Logan', 'name', false), 'Logan');
assert.equal(format('New York', 'place', false), 'New York');
assert.equal(format('Leonardo', 'person', false), 'Leonardo');
assert.equal(format('Your Uncle', 'person', false), 'your uncle');
assert.equal(format('your uncle', 'person', true), 'Your uncle');
const values = ['Logan', 'Red', 'Easton', 'Your Uncle', 'We Found It'];
const prompts = [['name'], ['color'], ['place'], ['person'], ['exclamation']];
const story = render('{0} packed a {1} bag in {2}. {3} helped. "{4}!" said {0}.', values, prompts, escape);
assert.equal(story.replace(/<[^>]+>/g, ''), 'Logan packed a red bag in Easton. Your uncle helped. "We found it!" said Logan.');
assert.equal(render('The robot replied, "{0}."', ['We Found It'], [['exclamation']], escape).replace(/<[^>]+>/g, ''), 'The robot replied, "We found it."');
assert.deepEqual(values, ['Logan', 'Red', 'Easton', 'Your Uncle', 'We Found It'], 'rendering never changes saved answers');
assert.equal(render('A {0}.', ['<img src=x>'], [['noun']], escape), 'A <span class="filled-word">&lt;img src=x&gt;</span>.');
console.log('PASS contextual answer case, names/places, sentence/quote starts, saved input preservation, escaping');
